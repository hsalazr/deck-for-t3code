#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md: name, version, license and full license text of
 * every package that ends up inside bin/plugin.js.
 *
 *   npm run notices
 *
 * The bundle (rollup.config.mjs) inlines the runtime imports of src/, which are
 * @elgato/streamdeck (and @elgato/utils, a type-only import in actions.ts) plus
 * their dependencies. This walks `dependencies` from those roots through
 * node_modules, so a dependency bump is picked up on the next run. The output
 * goes to the repo root and into the plugin folder (so it ships in the package).
 * Output is deterministic: no dates, sorted by name. Run it after `npm ci`,
 * before a release, and commit the result.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PLUGIN_DIR = "io.github.hsalazr.deck-for-t3code.sdPlugin";
const OUTPUTS = [path.join(ROOT, "THIRD_PARTY_NOTICES.md"), path.join(ROOT, PLUGIN_DIR, "THIRD_PARTY_NOTICES.md")];
/** The packages src/ imports at runtime. Everything they depend on comes along. */
export const ROOTS = ["@elgato/streamdeck", "@elgato/utils"];

/** Finds `name` the way Node would from `fromDir`: the nearest node_modules up the tree. */
function locate(name, fromDir) {
	for (let dir = fromDir; ; dir = path.dirname(dir)) {
		const candidate = path.join(dir, "node_modules", name);
		if (fs.existsSync(path.join(candidate, "package.json"))) return candidate;
		if (dir === path.dirname(dir)) return undefined;
	}
}

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|$|-)/i;

/** All bundled packages as `{name, version, license, text}`, sorted by name then version. */
export function collect(root = ROOT, roots = ROOTS) {
	const found = new Map();
	const visit = (name, fromDir) => {
		const dir = locate(name, fromDir);
		if (!dir) throw new Error(`${name} is not installed (run npm ci first)`);
		const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
		const key = `${pkg.name}@${pkg.version}`;
		if (found.has(key)) return;
		const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f) && fs.statSync(path.join(dir, f)).isFile()).sort();
		const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(" OR ") : "UNKNOWN");
		if (files.length === 0) throw new Error(`${key} ships no license file`);
		found.set(key, {
			name: pkg.name,
			version: pkg.version,
			license,
			homepage: pkg.homepage ?? (typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url) ?? "",
			text: files.map((f) => fs.readFileSync(path.join(dir, f), "utf8").trim()).join("\n\n"),
		});
		for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) {
			try {
				visit(dep, dir);
			} catch (error) {
				if (!(pkg.optionalDependencies && dep in pkg.optionalDependencies)) throw error;
			}
		}
	};
	for (const name of roots) visit(name, root);
	return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function render(packages) {
	const out = [
		"# Third-party notices",
		"",
		"Deck for T3 Code is released under the GPL-3.0-or-later (see `LICENSE`). The plugin bundle (`bin/plugin.js`)",
		"includes the following open-source packages, each under its own license. Their notices are reproduced below.",
		"",
		"Generated by `npm run notices` (scripts/notices.mjs); don't edit by hand.",
		"",
		"| Package | Version | License |",
		"|---|---|---|",
		...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
		"",
	];
	for (const p of packages) {
		out.push("---", "", `## ${p.name} ${p.version}`, "", `License: ${p.license}`);
		if (p.homepage) out.push(`Source: ${p.homepage}`);
		out.push("", "```text", p.text, "```", "");
	}
	return out.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const packages = collect();
	const markdown = render(packages);
	for (const file of OUTPUTS) fs.writeFileSync(file, markdown);
	console.log(`wrote ${OUTPUTS.length} notices files for ${packages.length} packages: ${packages.map((p) => `${p.name}@${p.version}`).join(", ")}`);
}
